/* =================================================================
   2. РАСЧЁТ СТОИМОСТИ
   Платформа и устройства считаются раздельно: на сайте и в прайсе
   они показываются отдельными строками, итог — их сумма.
   ================================================================= */
const SEASONS = ["low", "high"];

/** Множитель тарифа: Standard — 1, Premium — CONFIG.premiumMultiplier. */
function tierMultiplier(tier){
  return tier === "premium" ? CONFIG.premiumMultiplier : 1;
}

/** Платформа за месяц. От числа столиков не зависит. */
function platformFee(season, tier){
  return CONFIG.pricing[season].platform * tierMultiplier(tier);
}

/** Цена одного устройства в месяц. */
function devicePrice(season, tier){
  return CONFIG.pricing[season].device * tierMultiplier(tier);
}

/** Все устройства за месяц: каждое платное, с первого. */
function deviceFee(devices, season, tier){
  return devices * devicePrice(season, tier);
}

/** Итого за месяц в выбранный сезон. */
function monthlyFee(devices, season, tier){
  return platformFee(season, tier) + deviceFee(devices, season, tier);
}

/** Год целиком: каждый сезон × число его месяцев. */
function yearlyFee(devices, tier){
  const parts = { platform: 0, devices: 0 };
  SEASONS.forEach(s => {
    parts.platform += platformFee(s, tier) * CONFIG.pricing[s].months;
    parts.devices  += deviceFee(devices, s, tier) * CONFIG.pricing[s].months;
  });
  parts.total = parts.platform + parts.devices;
  return parts;
}
